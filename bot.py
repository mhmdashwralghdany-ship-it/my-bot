async def on_text(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    uid = update.message.from_user.id
    txt = update.message.text.strip()

    # أزرار نصية
    if txt in ["اسألة", "اسأله", "سؤال"]:
        await update.message.reply_text(f"💬 {random.choice(SARaha)}")
    elif txt in ["عبارات", "عبارة"]:
        await update.message.reply_text(f"😢 {random.choice(SAD_PHRASES)}")
    elif txt in ["نصيحة", "نصيحه"]:
        await update.message.reply_text(f"📝 {random.choice(ADVICE)}")
    elif txt in ["حكمة", "حكمه"]:
        await update.message.reply_text(f"💡 {random.choice(ADVICE)}")
    elif txt in ["نكتة", "نكته"]:
        await update.message.reply_text(f"😄 {random.choice(JOKES)}")
    elif txt in ["أنا مين", "انا مين"]:
        all_names = WHO_AM_I["anime"] + WHO_AM_I["football"] + WHO_AM_I["actors"] + WHO_AM_I["singers"] + WHO_AM_I["places"]
        await update.message.reply_text(f"🤔 أنت: {random.choice(all_names)}")
    elif txt in ["زخرفة", "زخرفه"]:
        USER_STATE[uid] = "waiting_name"
        await update.message.reply_text("✨ ابعت الاسم اللي عايز تزخرفه:")
    elif USER_STATE.get(uid) == "waiting_name":
        USER_STATE.pop(uid, None)
        decos = decorate_name(txt)
        msg = "\n".join(decos)
        await update.message.reply_text(f"✨ **زخارف اسمك:**\n\n{msg}")
    else:
        await update.message.reply_text(
            "🎮 اختر من الأزرار:",
            reply_markup=main_menu()
        )

